CODE_L1 = re.compile(r"^(\d{3})\s+(\S.+?)\s*$")
CODE_L2 = re.compile(r"^(\d{5})\s+(\S.+?)\s*$")
CODE_L3 = re.compile(r"^(\d{7})\b")
TOC_DOTS = re.compile(r"\.{2,}")


def parse_source(text: str) -> dict[str, dict]:
    """解析 PDF 抽取文本：同行「代码 名称」，三级行忽略。"""
    lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
    # 定位代码表正文：第二次出现「110 数学」（第一次在目录）
    hits = [i for i, ln in enumerate(lines) if re.match(r"^110\s+数学", ln) and not TOC_DOTS.search(ln)]
    start = hits[1] if len(hits) >= 2 else (hits[0] if hits else 0)

    tree: dict[str, dict] = {}
    current_l1: str | None = None
    current_l2: dict | None = None

    for ln in lines[start:]:
        if TOC_DOTS.search(ln):
            continue
        if CODE_L3.match(ln):
            # 三级学科说明可并入当前二级 desc
            if current_l2 is not None:
                rest = ln.split(None, 1)
                if len(rest) == 2:
                    piece = rest[1].strip()
                    if piece and piece not in current_l2["desc"]:
                        if current_l2["desc"]:
                            current_l2["desc"] += "；" + piece
                        else:
                            current_l2["desc"] = piece
            continue
        m2 = CODE_L2.match(ln)
        if m2:
            code5, name = m2.group(1), m2.group(2).strip()
            parent = code5[:3]
            if parent not in tree:
                # 有些二级可能出现在父级名缺失时
                tree[parent] = {"name": LEVEL1_GUIDE.get(parent, (parent,))[0], "children": []}
                current_l1 = parent
            elif current_l1 != parent and parent in tree:
                current_l1 = parent
            if not current_l1:
                continue
            if not code5.startswith(current_l1):
                # 跨到新的父级但未显式写出一级行
                if parent in CATEGORY_BY_L1:
                    current_l1 = parent
                    tree.setdefault(current_l1, {"name": LEVEL1_GUIDE.get(parent, (parent,))[0], "children": []})
                else:
                    continue
            current_l2 = {"code5": code5, "name": name, "desc": ""}
            tree[current_l1]["children"].append(current_l2)
            continue
        m1 = CODE_L1.match(ln)
        if m1:
            code, name = m1.group(1), m1.group(2).strip()
            if code not in CATEGORY_BY_L1:
                current_l1 = None
                current_l2 = None
                continue
            current_l1 = code
            tree.setdefault(code, {"name": name, "children": []})
            tree[code]["name"] = name
            current_l2 = None
            continue
        # 普通说明行
        if current_l2 is not None and ln and not ln[0].isdigit():
            if current_l2["desc"]:
                current_l2["desc"] += "；" + ln
            else:
                current_l2["desc"] = ln
    return tree


def dotted(code5: str) -> str:
    return f"{code5[:3]}.{code5[3:]}"


def course_query(name: str) -> str:
    """给教务公开检索用的关键词：去掉过长后缀，保留核心名称。"""
    q = name.strip()
    for junk in ("其他学科", "（参见", "(参见"):
        if junk in q:
            q = q.split(junk)[0].strip()
    # 「xxx学」保留；过长则取前缀
    if len(q) > 12:
        q = q[:12]
    return q


def clean_topic_text(desc: str) -> str:
    """把国标说明收成可读短句，去掉明显噪声。"""
    if not desc:
        return ""
    text = desc
    text = re.sub(r"参见\s*\d+.*?(?=；|$)", "", text)
    text = re.sub(r"见\s*\d+.*?(?=；|$)", "", text)
    text = re.sub(r"原名为.*?。(?=；|$)", "", text)
    text = re.sub(r"\s+", " ", text).strip(" ；;，,")
    parts = [p.strip(" ；;") for p in re.split(r"[；;]", text) if p.strip(" ；;")]
    # 去重保序
    seen = set()
    uniq = []
    for p in parts:
        if p in seen or len(p) < 2:
            continue
        seen.add(p)
        uniq.append(p)
    return "；".join(uniq)


def summarize_desc(desc: str, fallback: str, limit: int = 180) -> str:
    text = clean_topic_text(desc)
    if not text:
        return fallback
    parts = text.split("；")
    out = "；".join(parts[:6])
    if len(out) > limit:
        out = out[: limit - 1] + "…"
    return out


